export const STRINGS: Record<Lang, Strings> = { ru, en };

export function formatDate(iso: string, lang: Lang): string {
  const [y, m, d] = iso.split('-').map(Number);
  if (lang === 'ru') return `${d} ${ru.monthsGen[m - 1]} ${y}`;
  return `${en.months[m - 1]} ${d}, ${y}`;
}
